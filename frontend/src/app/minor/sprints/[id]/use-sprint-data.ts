"use client";

import { api } from "@/lib/api";
import { useState } from "react";
import type { MinorSprintFull, MinorSelfEvaluation, MinorTeacherAssessment } from "@/lib/api";

export function useSprintData(initialSprint: MinorSprintFull) {
  const [sprint, setSprint] = useState<MinorSprintFull>(initialSprint);

  // Dynamic Feedback Row State
  const [fbDate, setFbDate] = useState(new Date().toISOString().slice(0, 10));
  const [fbFromWhom, setFbFromWhom] = useState("");
  const [fbText, setFbText] = useState("");
  const [fbAction, setFbAction] = useState("");
  const [addingFeedback, setAddingFeedback] = useState(false);

  // Self Evaluation & Teacher Assessment Edit State
  const [selfEvals, setSelfEvals] = useState<MinorSelfEvaluation[]>(initialSprint.selfEvaluations || []);
  const [teacherAssessments, setTeacherAssessments] = useState<MinorTeacherAssessment[]>(initialSprint.teacherAssessments);
  const [savingEvals, setSavingEvals] = useState(false);
  const [evalSaveSuccess, setEvalSaveSuccess] = useState(false);

  // Reflection State
  const [refDate, setRefDate] = useState(initialSprint.reflection?.date || new Date().toISOString().slice(0, 10));
  const [whatLearned, setWhatLearned] = useState(initialSprint.reflection?.whatLearned || "");
  const [whatRetained, setWhatRetained] = useState(initialSprint.reflection?.whatRetained || "");
  const [whatChange, setWhatChange] = useState(initialSprint.reflection?.whatChange || "");
  const [savingReflection, setSavingReflection] = useState(false);
  const [refSaveSuccess, setRefSaveSuccess] = useState(false);

  async function reloadSprint(keepLocalEvals = false) {
    try {
      const updated = await api.minor.sprints.get(sprint.id);
      setSprint(updated);
      if (!keepLocalEvals) {
        setSelfEvals(updated.selfEvaluations);
        setTeacherAssessments(updated.teacherAssessments);
      }
      if (updated.reflection) {
        setRefDate(updated.reflection.date);
        setWhatLearned(updated.reflection.whatLearned || "");
        setWhatRetained(updated.reflection.whatRetained || "");
        setWhatChange(updated.reflection.whatChange || "");
      }
    } catch (err) {
      console.error("Failed to reload sprint:", err);
    }
  }

  // Feedback Helpers
  async function handleAddFeedback(e: React.FormEvent) {
    e.preventDefault();
    if (!fbFromWhom.trim() || !fbText.trim() || !fbAction.trim()) return;
    setAddingFeedback(true);
    try {
      await api.minor.sprints.feedback.create(sprint.id, {
        date: fbDate,
        fromWhom: fbFromWhom.trim(),
        feedback: fbText.trim(),
        action: fbAction.trim(),
      });
      setFbFromWhom("");
      setFbText("");
      setFbAction("");
      await reloadSprint();
    } catch (err) {
      console.error("Failed to add feedback:", err);
    } finally {
      setAddingFeedback(false);
    }
  }

  async function handleDeleteFeedback(id: number) {
    try {
      await api.minor.sprints.feedback.delete(id);
      await reloadSprint();
    } catch (err) {
      console.error("Failed to delete feedback:", err);
    }
  }

  // Self Evaluation Helpers
  async function handleAutoPopulateEvals() {
    try {
      const autoGenerated = await api.minor.sprints.autoSelfEvaluations(sprint.id);
      setSelfEvals(autoGenerated);
      await reloadSprint();
    } catch (err) {
      console.error("Failed to auto-populate self evals:", err);
    }
  }

  function handlePopulateSingleLuEvidence(luNum: number) {
    const storiesForLu = sprint.stories.filter((s) => s.learningOutcomes.includes(luNum));
    const completedStories = storiesForLu.filter((s) => s.status === "done");
    const inProgressStories = storiesForLu.filter((s) => s.status !== "done");

    const lines: string[] = [];
    if (completedStories.length > 0) {
      lines.push(`Voltooide stories voor LU ${luNum}:`);
      for (const st of completedStories) {
        const prefix = st.storyNumber ? `[${st.storyNumber}] ` : "";
        lines.push(`• ${prefix}${st.title}`);
        if (st.evidence && st.evidence.length > 0) {
          for (const ev of st.evidence) {
            lines.push(`   - Bewijs (${ev.type}): ${ev.title} (${ev.url})`);
          }
        }
      }
    }
    if (inProgressStories.length > 0) {
      if (lines.length > 0) lines.push("");
      lines.push(`In uitvoering:`);
      for (const st of inProgressStories) {
        const prefix = st.storyNumber ? `[${st.storyNumber}] ` : "";
        lines.push(`• ${prefix}${st.title}`);
      }
    }
    if (lines.length === 0) {
      lines.push(`Geen stories gekoppeld aan LU ${luNum} in deze sprint.`);
    }

    const generated = lines.join("\n");
    const isRealized = completedStories.length > 0;

    setSelfEvals((prev) =>
      prev.map((item) => {
        if (item.learningOutcome === luNum) {
          const currentArg = (item.argumentation || "").trim();
          const newArg = currentArg && !currentArg.startsWith("Geen stories")
            ? `${currentArg}\n\n${generated}`
            : generated;
          return {
            ...item,
            level: isRealized ? "V" : item.level,
            argumentation: newArg,
          };
        }
        return item;
      })
    );
  }

  function handleAppendEvidenceToLu(luNum: number, ev: { type: string; title: string; url: string }) {
    const textToAppend = `- Bewijs (${ev.type}): ${ev.title} (${ev.url})`;
    setSelfEvals((prev) =>
      prev.map((item) => {
        if (item.learningOutcome === luNum) {
          const current = (item.argumentation || "").trim();
          const newArg = current ? `${current}\n${textToAppend}` : textToAppend;
          return {
            ...item,
            argumentation: newArg,
          };
        }
        return item;
      })
    );
  }

  async function handleSaveEvalsAndAssessments() {
    setSavingEvals(true);
    try {
      await api.minor.sprints.saveSelfEvaluations(
        sprint.id,
        selfEvals.map((e) => ({
          learningOutcome: e.learningOutcome,
          level: e.level,
          argumentation: e.argumentation || "",
        }))
      );
      await api.minor.sprints.saveTeacherAssessments(
        sprint.id,
        teacherAssessments.map((a) => ({
          learningOutcome: a.learningOutcome,
          assessment: a.assessment,
          notes: a.notes || "",
        }))
      );
      setEvalSaveSuccess(true);
      setTimeout(() => setEvalSaveSuccess(false), 3000);
      await reloadSprint(true);
    } catch (err) {
      console.error("Failed to save evaluations:", err);
    } finally {
      setSavingEvals(false);
    }
  }

  // Reflection Helpers
  async function handleSaveReflection(e?: React.FormEvent) {
    if (e) e.preventDefault();
    setSavingReflection(true);
    try {
      await Promise.all([
        api.minor.sprints.saveReflection(sprint.id, {
          date: refDate,
          whatLearned,
          whatRetained,
          whatChange,
        }),
        api.minor.sprints.saveTeacherAssessments(
          sprint.id,
          teacherAssessments.map((a) => ({
            learningOutcome: a.learningOutcome,
            assessment: a.assessment,
            notes: a.notes || "",
          }))
        ),
      ]);
      setRefSaveSuccess(true);
      setTimeout(() => setRefSaveSuccess(false), 3000);
      await reloadSprint();
    } catch (err) {
      console.error("Failed to save reflection:", err);
    } finally {
      setSavingReflection(false);
    }
  }

  // Helper to build latest current full sprint data including unsaved form state
  function getCurrentFullSprint(): MinorSprintFull {
    return {
      ...sprint,
      selfEvaluations: selfEvals,
      teacherAssessments: teacherAssessments,
      reflection: sprint.reflection ? {
        ...sprint.reflection,
        date: refDate,
        whatLearned,
        whatRetained,
        whatChange,
      } : {
        id: 0,
        sprintId: sprint.id,
        date: refDate,
        whatLearned,
        whatRetained,
        whatChange,
        createdAt: "",
        updatedAt: new Date().toISOString(),
      },
    };
  }

  return {
    sprint,
    setSprint,
    fbDate,
    setFbDate,
    fbFromWhom,
    setFbFromWhom,
    fbText,
    setFbText,
    fbAction,
    setFbAction,
    addingFeedback,
    setAddingFeedback,
    selfEvals,
    setSelfEvals,
    teacherAssessments,
    setTeacherAssessments,
    savingEvals,
    setSavingEvals,
    evalSaveSuccess,
    setEvalSaveSuccess,
    refDate,
    setRefDate,
    whatLearned,
    setWhatLearned,
    whatRetained,
    setWhatRetained,
    whatChange,
    setWhatChange,
    savingReflection,
    setSavingReflection,
    refSaveSuccess,
    setRefSaveSuccess,
    reloadSprint,
    handleAddFeedback,
    handleDeleteFeedback,
    handleAutoPopulateEvals,
    handlePopulateSingleLuEvidence,
    handleAppendEvidenceToLu,
    handleSaveEvalsAndAssessments,
    handleSaveReflection,
    getCurrentFullSprint,
  };
}
